pub fn annotation(cp: u32) -> bool {
    cp == 0x20
        || cp == 0x2e
        || (0x300..=0x36f).contains(&cp)
        || matches!(
            cp,
            0x2c8
                | 0x2cc
                | 0x2d0
                | 0x2d1
                | 0x2de
                | 0xa71b
                | 0xa71c
                | 0x2b0
                | 0x2b1
                | 0x2b2
                | 0x2b7
                | 0x2e0
                | 0x2e4
                | 0x207f
                | 0x2e1
        )
        || (0x2e5..=0x2e9).contains(&cp)
}
