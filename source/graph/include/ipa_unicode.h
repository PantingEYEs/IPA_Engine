inline bool ipa_annotation(std::uint32_t cp) noexcept {
    return cp == ' ' || cp == '.' || (cp >= 0x300 && cp <= 0x36f)
        || cp == 0x2c8 || cp == 0x2cc || cp == 0x2d0 || cp == 0x2d1 || cp == 0x2de
        || (cp >= 0x2e5 && cp <= 0x2e9) || cp == 0xa71b || cp == 0xa71c
        || cp == 0x2b0 || cp == 0x2b1 || cp == 0x2b2 || cp == 0x2b7
        || cp == 0x2e0 || cp == 0x2e4 || cp == 0x207f || cp == 0x2e1;
}
